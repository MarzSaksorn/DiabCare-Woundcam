create type public.user_role as enum ('user', 'admin');
create type public.patient_sex as enum ('FEMALE', 'MALE');

create table public.users (
  id bigint generated by default as identity primary key,
  open_id varchar(64) not null unique,
  name text,
  email varchar(320),
  login_method varchar(64),
  role public.user_role not null default 'user',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_signed_in timestamptz not null default now()
);

create table public.diabetes_import_batches (
  id bigint generated by default as identity primary key,
  source_filename varchar(255) not null,
  file_sha256 varchar(64) not null unique,
  source_record_count integer not null check (source_record_count >= 0),
  created_at timestamptz not null default now()
);

create table public.diabetes_patients (
  id bigint generated by default as identity primary key,
  import_batch_id bigint not null references public.diabetes_import_batches(id) on delete restrict,
  source_row_number integer not null check (source_row_number > 0),
  age varchar(32) not null,
  identify_by varchar(32) not null,
  type1 smallint not null check (type1 in (0, 1)),
  type2 smallint not null check (type2 in (0, 1)),
  gdm smallint not null check (gdm in (0, 1)),
  sex public.patient_sex not null,
  dm_onset smallint not null check (dm_onset in (0, 1)),
  created_at timestamptz not null default now(),
  constraint diabetes_patients_batch_row_unique unique (import_batch_id, source_row_number)
);

create table public.diabetes_patient_observations (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.diabetes_patients(id) on delete cascade,
  source_column varchar(128) not null,
  dictionary_field varchar(128) not null,
  period_key integer,
  value_number numeric(18, 6),
  value_text text,
  created_at timestamptz not null default now(),
  constraint diabetes_observations_patient_column_unique unique (patient_id, source_column),
  constraint diabetes_observations_value_check check (value_number is not null or value_text is not null)
);

create index diabetes_patients_import_batch_idx on public.diabetes_patients(import_batch_id);
create index diabetes_observations_patient_idx on public.diabetes_patient_observations(patient_id);
create index diabetes_observations_dictionary_period_idx on public.diabetes_patient_observations(dictionary_field, period_key);

alter table public.users enable row level security;
alter table public.diabetes_import_batches enable row level security;
alter table public.diabetes_patients enable row level security;
alter table public.diabetes_patient_observations enable row level security;

revoke all on table public.users, public.diabetes_import_batches, public.diabetes_patients, public.diabetes_patient_observations from anon, authenticated;
grant all on table public.users, public.diabetes_import_batches, public.diabetes_patients, public.diabetes_patient_observations to service_role;
