create table if not exists public.patient_wound_media (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.registered_patients(id) on delete restrict,
  wound_assessment_id bigint references public.patient_wound_assessments(id) on delete set null,
  storage_key text not null unique,
  storage_url text not null,
  file_name varchar(240) not null,
  mime_type varchar(80) not null check (mime_type in ('image/jpeg', 'image/png', 'image/webp')),
  file_size_bytes integer not null check (file_size_bytes > 0 and file_size_bytes <= 12582912),
  caption varchar(500),
  captured_on date,
  recorded_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists patient_wound_media_patient_date_idx on public.patient_wound_media (patient_id, created_at desc);
create index if not exists patient_wound_media_wound_idx on public.patient_wound_media (wound_assessment_id);

alter table public.patient_wound_media enable row level security;
revoke all on table public.patient_wound_media from anon, authenticated;
grant all on table public.patient_wound_media to service_role;

comment on table public.patient_wound_media is 'Clinician-uploaded wound photographs. Bytes live in managed object storage; this table stores protected metadata and references.';
