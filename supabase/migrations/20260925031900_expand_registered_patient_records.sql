alter table public.registered_patients
  add column if not exists allergies_summary text,
  add column if not exists diagnoses_summary text,
  add column if not exists risk_flags text,
  add column if not exists care_team text,
  add column if not exists archived_at timestamptz,
  add column if not exists archived_by_user_id bigint references public.users(id) on delete set null,
  add column if not exists archive_reason text;

create index if not exists registered_patients_active_created_at_idx
  on public.registered_patients (created_at desc)
  where archived_at is null;

create table public.patient_medications (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.registered_patients(id) on delete restrict,
  medication_name varchar(160) not null,
  dose varchar(80),
  route varchar(80),
  frequency varchar(120),
  started_on date,
  ended_on date,
  status varchar(32) not null default 'active' check (status in ('active', 'paused', 'stopped', 'completed')),
  notes text,
  recorded_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint patient_medications_date_order_check check (ended_on is null or started_on is null or ended_on >= started_on)
);
create index patient_medications_patient_idx on public.patient_medications (patient_id, created_at desc);

create table public.patient_wound_assessments (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.registered_patients(id) on delete restrict,
  wound_label varchar(160) not null,
  location varchar(160) not null,
  assessed_on date not null,
  classification varchar(80),
  length_cm numeric(10, 2),
  width_cm numeric(10, 2),
  depth_cm numeric(10, 2),
  tissue_characteristics text,
  drainage varchar(80),
  odor varchar(80),
  pain_score integer check (pain_score is null or (pain_score >= 0 and pain_score <= 10)),
  infection_indicators text,
  treatment_plan text,
  clinician_notes text,
  media_reference text,
  recorded_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint patient_wound_measurement_check check (length_cm is null or length_cm >= 0) ,
  constraint patient_wound_width_check check (width_cm is null or width_cm >= 0),
  constraint patient_wound_depth_check check (depth_cm is null or depth_cm >= 0)
);
create index patient_wound_assessments_patient_date_idx on public.patient_wound_assessments (patient_id, assessed_on desc);

create table public.patient_record_audit_events (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.registered_patients(id) on delete restrict,
  actor_user_id bigint references public.users(id) on delete set null,
  event_type varchar(48) not null,
  summary varchar(240) not null,
  created_at timestamptz not null default now()
);
create index patient_record_audit_patient_date_idx on public.patient_record_audit_events (patient_id, created_at desc);

alter table public.patient_medications enable row level security;
alter table public.patient_wound_assessments enable row level security;
alter table public.patient_record_audit_events enable row level security;
revoke all on table public.patient_medications, public.patient_wound_assessments, public.patient_record_audit_events from anon, authenticated;
grant all on table public.patient_medications, public.patient_wound_assessments, public.patient_record_audit_events to service_role;

comment on table public.patient_medications is 'Clinician-entered medication history for registered patients.';
comment on table public.patient_wound_assessments is 'Clinician-entered wound and healing assessments. Measurements are observations, not diagnoses.';
comment on table public.patient_record_audit_events is 'Server-side audit trail for patient record changes and exports.';
