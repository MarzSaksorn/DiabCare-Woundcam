create table public.diabetes_example_import_batches (
  id bigint generated by default as identity primary key,
  source_filename varchar(255) not null,
  file_sha256 varchar(64) not null unique,
  source_record_count integer not null check (source_record_count >= 0),
  exact_duplicate_group_count integer not null default 0 check (exact_duplicate_group_count >= 0),
  exact_duplicate_extra_count integer not null default 0 check (exact_duplicate_extra_count >= 0),
  mapping_version varchar(32) not null,
  status varchar(32) not null check (status in ('validated', 'imported', 'failed')),
  created_at timestamptz not null default now()
);

create table public.diabetes_example_records (
  id bigint generated by default as identity primary key,
  import_batch_id bigint not null references public.diabetes_example_import_batches(id) on delete restrict,
  source_row_number integer not null check (source_row_number > 0),
  row_sha256 varchar(64) not null,
  exact_duplicate_group varchar(64),
  is_exact_duplicate boolean not null default false,
  year integer not null,
  gender varchar(32) not null,
  age numeric(10,4) not null,
  location varchar(128) not null,
  race_african_american smallint not null check (race_african_american in (0, 1)),
  race_asian smallint not null check (race_asian in (0, 1)),
  race_caucasian smallint not null check (race_caucasian in (0, 1)),
  race_hispanic smallint not null check (race_hispanic in (0, 1)),
  race_other smallint not null check (race_other in (0, 1)),
  hypertension smallint not null check (hypertension in (0, 1)),
  heart_disease smallint not null check (heart_disease in (0, 1)),
  smoking_history varchar(32) not null,
  bmi numeric(10,4) not null,
  hba1c_level numeric(10,4) not null,
  blood_glucose_level integer not null,
  diabetes_label smallint not null check (diabetes_label in (0, 1)),
  clinical_notes text not null,
  created_at timestamptz not null default now(),
  constraint diabetes_example_records_batch_row_unique unique (import_batch_id, source_row_number),
  constraint diabetes_example_records_race_one_hot check (
    race_african_american + race_asian + race_caucasian + race_hispanic + race_other = 1
  )
);

create index diabetes_example_records_batch_row_idx
  on public.diabetes_example_records (import_batch_id, source_row_number);
create index diabetes_example_records_batch_year_idx
  on public.diabetes_example_records (import_batch_id, year);
create index diabetes_example_records_batch_label_idx
  on public.diabetes_example_records (import_batch_id, diabetes_label);
create index diabetes_example_records_row_hash_idx
  on public.diabetes_example_records (import_batch_id, row_sha256);

alter table public.diabetes_example_import_batches enable row level security;
alter table public.diabetes_example_records enable row level security;

create policy diabetes_example_import_batches_deny_api_access
  on public.diabetes_example_import_batches
  for all to anon, authenticated
  using (false)
  with check (false);

create policy diabetes_example_records_deny_api_access
  on public.diabetes_example_records
  for all to anon, authenticated
  using (false)
  with check (false);

revoke all on table public.diabetes_example_import_batches from anon, authenticated;
revoke all on table public.diabetes_example_records from anon, authenticated;

