create table public.registered_patients (
  id bigint generated by default as identity primary key,
  patient_code varchar(64) not null unique,
  display_name varchar(160),
  phone varchar(32),
  date_of_birth date,
  age integer check (age is null or (age >= 0 and age <= 150)),
  registration_location varchar(160) not null,
  identify_by varchar(32) not null,
  type1 smallint not null default 0 check (type1 in (0, 1)),
  type2 smallint not null default 0 check (type2 in (0, 1)),
  gdm smallint not null default 0 check (gdm in (0, 1)),
  sex public.patient_sex not null,
  clinical_notes text,
  created_by_user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint registered_patients_identity_check check (length(btrim(patient_code)) >= 2),
  constraint registered_patients_diabetes_context_check check (type1 + type2 + gdm <= 1),
  constraint registered_patients_age_or_dob_check check (age is not null or date_of_birth is not null)
);

create index registered_patients_created_at_idx on public.registered_patients (created_at desc);
create index registered_patients_location_idx on public.registered_patients (registration_location);
create index registered_patients_name_search_idx on public.registered_patients using btree (lower(display_name));

alter table public.registered_patients enable row level security;
revoke all on table public.registered_patients from anon, authenticated;
grant all on table public.registered_patients to service_role;

comment on table public.registered_patients is
  'Clinician-created patient registrations. Protected server-side; separate from source-preserved imported cohorts.';
comment on column public.registered_patients.patient_code is
  'Local facility identifier. Do not use national identifiers unless approved by local governance.';
comment on column public.registered_patients.clinical_notes is
  'Clinician-entered notes. Treat as sensitive health information.';
